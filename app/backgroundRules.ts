import type { CatalogOption } from "./catalog";
import { documentBackgrounds } from "./documentBackgrounds";

export type BackgroundFeature = { name: string; description: string };
export type BackgroundRule = {
  skills: string[];
  skillChoice?: string;
  tools: string[];
  toolChoice?: string;
  languageChoices: number;
  languageNote?: string;
  equipment: string[];
  feature: BackgroundFeature;
};

/**
 * Starting coins are tracked in the character wallet, not as a line item in
 * inventory.  The PHB background lists phrase this either as "Кошель с N зм"
 * or simply "N зм" (the hermit is the latter), so keep that small variation
 * in one place rather than leaking it into every sheet/export.
 */
export function startingGoldFromBackgroundEquipment(equipment: string[]) {
  return equipment.reduce((total, item) => {
    const match = item.match(/(?:кошел(?:[её]к|ь)\s+с\s+)?(\d+)\s*зм\b/i);
    return total + (match ? Number(match[1]) : 0);
  }, 0);
}

export function backgroundEquipmentWithoutStartingGold(equipment: string[]) {
  return equipment.filter(item => !/(?:кошел(?:[её]к|ь)\s+с\s+)?\d+\s*зм\b/i.test(item));
}

export function backgroundStartingGold(id: string, fallback?: CatalogOption) {
  return startingGoldFromBackgroundEquipment(backgroundRule(id, fallback).equipment);
}

const B = (
  skills: string[],
  tools: string[],
  languageChoices: number,
  equipment: string[],
  name: string,
  description: string,
): BackgroundRule => ({ skills, tools, languageChoices, equipment, feature: { name, description } });

const normaliseSkill = (skill: string) => skill === "Восприятие" ? "Внимательность" : skill;

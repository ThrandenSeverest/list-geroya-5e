export function normalizedItemName(name:string):string {
 return name.toLowerCase().replace(/ё/g,'е').replace(/\s*[×x]\s*\d+\s*$/i,'').replace(/\s*\+[123]\s*$/,'').replace(/\s*\((?:кд\b|[+]?\d+\s*к\s*кд)[^)]*\)/ig,'').trim();
}
export function catalogItemFor(name:string):CatalogItem|undefined {
 const key=normalizedItemName(name);
 const redirected=aliases[key] ? normalizedItemName(aliases[key]) : key;
 return itemCatalog.find(item=>normalizedItemName(item.name)===redirected || item.aliases?.some(a=>normalizedItemName(a)===redirected))
   || itemCatalog.find(item=>(item.category==='armor'||item.category==='focus') && redirected.startsWith(normalizedItemName(item.name)+' ('));
}
export function currencyLabel(gp?:number):string {
 if(gp===undefined)return '—';
 if(gp>=1)return gp+' зм';
 if(gp>=0.1)return Math.round(gp*10)+' см';
 return Math.round(gp*100)+' мм';
}

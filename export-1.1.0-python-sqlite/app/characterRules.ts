function pactMagic(level: number) {
  if (level < 1) return { slots: 0, level: 0 };
  const slotLevel = Math.min(5, Math.ceil(level / 2));
  const slots = level === 1 ? 1 : level < 11 ? 2 : level < 17 ? 3 : 4;
  return { slots, level: slotLevel };
}

function casterSlots(classId: string, level: number) {
  if (["bard", "cleric", "druid", "sorcerer", "wizard"].includes(classId)) return fullCasterSlots[level] || [];
  if (["paladin", "ranger"].includes(classId)) return fullCasterSlots[Math.floor(level / 2)] || [];
  if (classId === "artificer") return fullCasterSlots[Math.ceil(level / 2)] || [];
  return [];
}

function maximumSpellLevel(classId: string, level: number) {
  if (classId === "warlock") return pactMagic(level).level;
  return casterSlots(classId, level).length;
}

function knownSpellLevelLimits(classId: string, level: number, knownTable: number[]) {
  const limits = Array.from({ length: maximumSpellLevel(classId, level) + 1 }, () => 0);
  for (let circle = 1; circle < limits.length; circle += 1) {
    let reachable = 0;
    for (let classLevel = 1; classLevel <= level; classLevel += 1) {
      if (maximumSpellLevel(classId, classLevel) < circle) continue;
      reachable += Math.max(0, (knownTable[classLevel] || 0) - (knownTable[classLevel - 1] || 0));
      if (classLevel > 1 && (knownTable[classLevel - 1] || 0) > 0) reachable += 1;
    }
    limits[circle] = Math.min(knownTable[level] || 0, reachable);
  }
  return limits;
}

export function spellSelectionRuleForClass(character: ExportCharacter, classId: string, classLevel?: number): SpellSelectionRule {
  const level = classLevel ?? character.level;
  const cantrips = cantripTables[classId]?.[level] || 0;
  const ability = classId === "wizard" || classId === "artificer" ? "int" : ["cleric", "druid", "ranger"].includes(classId) ? "wis" : "cha";
  const mod = Math.floor(((character.abilities[ability as AbilityKey] || 10) - 10) / 2);
  if (classId === "warlock") {
    const pact = pactMagic(level);
    return { caster: true, mode: "known", title: "Известные заклинания", cantrips, leveled: warlockKnown[level], maxLevel: pact.level, slots: [], pact, levelLimits: knownSpellLevelLimits(classId, level, warlockKnown) };
  }
  const slots = casterSlots(classId, level);
  const maxLevel = slots.length;
  if (classId === "bard") return { caster: true, mode: "known", title: "Известные заклинания", cantrips, leveled: bardKnown[level], maxLevel, slots, levelLimits: knownSpellLevelLimits(classId, level, bardKnown) };
  if (classId === "sorcerer") return { caster: true, mode: "known", title: "Известные заклинания", cantrips, leveled: sorcererKnown[level], maxLevel, slots, levelLimits: knownSpellLevelLimits(classId, level, sorcererKnown) };
  if (classId === "ranger") return { caster: level >= 2, mode: "known", title: "Известные заклинания", cantrips: 0, leveled: rangerKnown[level], maxLevel, slots, levelLimits: knownSpellLevelLimits(classId, level, rangerKnown) };
  if (classId === "wizard") {
    const prepared = Math.max(1, mod + level);
    return { caster: true, mode: "spellbook", title: "Заклинания в книге", cantrips, leveled: 6 + Math.max(0, level - 1) * 2, prepared, maxLevel, slots };
  }
  if (classId === "cleric" || classId === "druid") {
    const prepared = Math.max(1, mod + level);
    return { caster: true, mode: "prepared", title: "Подготовленные заклинания", cantrips, leveled: prepared, prepared, maxLevel, slots };
  }
  if (classId === "paladin") {
    const prepared = level < 2 ? 0 : Math.max(1, mod + Math.floor(level / 2));
    return { caster: level >= 2, mode: "prepared", title: "Подготовленные заклинания", cantrips: 0, leveled: prepared, prepared, maxLevel, slots };
  }
  if (classId === "artificer") {
    const prepared = Math.max(1, mod + Math.ceil(level / 2));
    return { caster: true, mode: "prepared", title: "Подготовленные заклинания", cantrips, leveled: prepared, prepared, maxLevel, slots };
  }
  return { caster: false, mode: "none", title: "Нет базового заклинательства", cantrips: 0, leveled: 0, maxLevel: 0, slots: [] };
}

export function spellSelectionRule(character: ExportCharacter): SpellSelectionRule {
  return spellSelectionRuleForClass(character, character.className, character.level);
}


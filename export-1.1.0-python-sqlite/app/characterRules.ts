export function isTashaAdditionalSpell(character: Pick<ExportCharacter, "className" | "useTasha" | "tceFullBanned">, spellId: string) {
  // Expanded class lists are published TCE content, not Optional Class Features.
  // The separate optional-feature checkbox must never remove them.
  return !character.tceFullBanned && Boolean(tashaAdditionalSpellIds[character.className]?.includes(spellId));
}

export function spellAvailableToCharacter(character: Pick<ExportCharacter, "className" | "subclass" | "level" | "useTasha" | "tceFullBanned">, spell: CatalogSpell) {
  if (spell.classes.includes(character.className)) return true;
  if (isTashaAdditionalSpell(character, spell.id)) return true;
  const subclass = selectedSubclass(character.className, character.subclass || "");
  if (subclass?.expandedSpells?.includes(spell.id)) return true;
  if (subclassSpellGrants(character).some(grant => grant.mode === "expanded" && grant.refs.some(ref => spellMatchesRef(spell, ref)))) return true;
  if (character.className === "sorcerer" && character.subclass === "divinesoul" && spell.classes.includes("cleric")) return true;
  return false;
}

function recommendedLevelTargets(character: ExportCharacter, rule: SpellSelectionRule, catalog: CatalogSpell[]) {
  const counts = Array.from({ length: rule.maxLevel + 1 }, () => 0);
  if (!rule.leveled || !rule.maxLevel) return counts;

  // A wizard begins with six 1st-circle spells, then adds two spells at every
  // wizard level. A ready-made level-8 book therefore becomes 8/4/4/4, not
  // fifteen 1st-circle spells followed by a few accidental higher picks.
  if (character.className === "wizard") {
    counts[1] = Math.min(6, rule.leveled);
    for (let classLevel = 2; classLevel <= character.level; classLevel += 1) {
      const circle = maximumSpellLevel("wizard", classLevel);
      counts[circle] += Math.min(2, rule.leveled - counts.reduce((total, value) => total + value, 0));
    }
    return counts;
  }

  const availableLevels = Array.from({ length: rule.maxLevel }, (_, index) => index + 1)
    .filter(level => catalog.some(spell => spell.level === level));
  const canAdd = (level: number) => !rule.levelLimits?.some((limit, circle) =>
    circle > 0 && circle <= level && counts.slice(circle).reduce((total, value) => total + value, 0) >= limit,
  );
  for (let pick = 0; pick < rule.leveled; pick += 1) {
    const candidates = availableLevels.filter(canAdd);
    if (!candidates.length) break;
    const level = candidates.sort((a, b) => {
      const aWeight = rule.pact ? 1 : (rule.slots[a - 1] || 1);
      const bWeight = rule.pact ? 1 : (rule.slots[b - 1] || 1);
      return (bWeight / (counts[b] + 1)) - (aWeight / (counts[a] + 1)) || b - a;
    })[0];
    counts[level] += 1;
  }
  return counts;
}

function rankedSpellCatalog(character: ExportCharacter, catalog: CatalogSpell[]) {
  const order = recommendations[character.className] || [];
  return [...catalog].sort((a, b) => {
    const ai = order.indexOf(a.id);
    const bi = order.indexOf(b.id);
    return (ai < 0 ? 999 : ai) - (bi < 0 ? 999 : bi) || a.name.localeCompare(b.name, "ru");
  });
}

export type AlwaysPreparedSpell = { id: string; source: string };

export function alwaysPreparedSpellEntries(character: ExportCharacter, catalog: CatalogSpell[]): AlwaysPreparedSpell[] {
  const maximum = spellSelectionRule(character).maxLevel;
  const subclass = selectedSubclass(character.className, character.subclass || "");
  const entries: AlwaysPreparedSpell[] = (subclass?.alwaysPrepared || []).map(id => ({ id, source: subclass?.name || "Подкласс" }));
  for (const grant of subclassSpellGrants(character)) {
    if (grant.mode === "expanded") continue;
    for (const ref of grant.refs) {
      const spell = catalog.find(item => spellMatchesRef(item, ref));
      if (spell) entries.push({ id: spell.id, source: grant.mode === "known" ? `${subclass?.name || "Подкласс"} · автоматически известно` : subclass?.name || "Подкласс" });
    }
  }
  for (const id of selectedSubclassSpellChoiceIds(character)) entries.push({ id, source: subclass?.name || "Подкласс" });
  if (character.useTasha && !character.tceFullBanned && character.className === "ranger" && character.level >= 3) entries.push({ id: "speak-with-animals", source: "Первозданная осведомлённость (TCE)" });
  return entries
    .filter(entry => {
      const spell = catalog.find(item => item.id === entry.id);
      return Boolean(spell) && spell!.level <= maximum;
    })
    .filter((entry, index, all) => all.findIndex(item => item.id === entry.id) === index);
}

export function alwaysPreparedSpellIds(character: ExportCharacter, catalog: CatalogSpell[]) {
  return alwaysPreparedSpellEntries(character, catalog).map(entry => entry.id);
}

export function optimalSpellIds(character: ExportCharacter, catalog: CatalogSpell[]) {
  const rule = spellSelectionRule(character);
  const alwaysPrepared = new Set(alwaysPreparedSpellIds(character, catalog));
  const allowed = catalog.filter(spell =>
    spellAvailableToCharacter(character, spell) && spell.level <= rule.maxLevel && !alwaysPrepared.has(spell.id),
  );
  const ranked = rankedSpellCatalog(character, allowed);
  const targets = recommendedLevelTargets(character, rule, allowed);
  const leveled = targets.flatMap((count, level) =>
    level > 0 ? ranked.filter(spell => spell.level === level).slice(0, count) : [],
  );
  const selected = new Set(leveled.map(spell => spell.id));
  for (const spell of ranked.filter(item => item.level > 0)) {
    if (selected.size >= rule.leveled) break;
    if (!selected.has(spell.id)) selected.add(spell.id);
  }
  return [
    ...ranked.filter(spell => spell.level === 0).slice(0, rule.cantrips).map(spell => spell.id),
    ...selected,
  ];
}

export function optimalPreparedSpellIds(character: ExportCharacter, catalog: CatalogSpell[], selectedSpellIds: string[]) {
  const rule = spellSelectionRule(character);
  if (rule.mode !== "spellbook" || !rule.prepared) return [];
  const selected = new Set(selectedSpellIds);
  const ranked = rankedSpellCatalog(character, catalog).filter(spell => spell.level > 0 && selected.has(spell.id));
  const byLevel = Array.from({ length: rule.maxLevel + 1 }, (_, level) => ranked.filter(spell => spell.level === level));
  const targets = Array.from({ length: rule.maxLevel + 1 }, () => 0);
  let remaining = Math.min(rule.prepared, ranked.length);

  // A useful high-level prepared list must actually contain answers from every
  // accessible circle. Reserve one choice from the highest circles first;
  // then distribute the rest according to available slots and current density.
  for (let level = rule.maxLevel; level >= 1 && remaining > 0; level -= 1) {
    if (byLevel[level].length) {
      targets[level] += 1;
      remaining -= 1;
    }
  }
  while (remaining > 0) {
    const candidates = byLevel
      .map((available, level) => ({ level, available: available.length }))
      .filter(({ level, available }) => level > 0 && targets[level] < available)
      .sort((left, right) => {
        const leftWeight = (rule.slots[left.level - 1] || 1) / (targets[left.level] + 1);
        const rightWeight = (rule.slots[right.level - 1] || 1) / (targets[right.level] + 1);
        return rightWeight - leftWeight || right.level - left.level;
      });
    if (!candidates.length) break;
    targets[candidates[0].level] += 1;
    remaining -= 1;
  }
  return targets.flatMap((count, level) => byLevel[level].slice(0, count).map(spell => spell.id));
}

export const pointBuyCost: Record<number, number> = { 8: 0, 9: 1, 10: 2, 11: 3, 12: 4, 13: 5, 14: 7, 15: 9 };
export function pointBuySpent(scores: AbilityScores) {
  return (Object.values(scores) as number[]).reduce((total, score) => total + (pointBuyCost[Math.max(8, Math.min(15, score))] ?? 0), 0);
}

const legalPointBuyBuilds: AbilityScores[] = [];
for (let str = 8; str <= 15; str += 1) for (let dex = 8; dex <= 15; dex += 1) for (let con = 8; con <= 15; con += 1)
  for (let int = 8; int <= 15; int += 1) for (let wis = 8; wis <= 15; wis += 1) for (let cha = 8; cha <= 15; cha += 1) {
    const abilities = { str, dex, con, int, wis, cha };
    if (pointBuySpent(abilities) === 27) legalPointBuyBuilds.push(abilities);
  }

const physicalPrimary: Record<string, AbilityKey> = {
  barbarian: "str", fighter: "str", monk: "dex", paladin: "str", ranger: "dex", rogue: "dex",
};

function distinctAbilitySelections(count: number, keys: AbilityKey[], prefix: AbilityKey[] = []): AbilityKey[][] {
  if (!count) return [prefix];
  return keys.flatMap((key, index) => distinctAbilitySelections(count - 1, keys.slice(index + 1), [...prefix, key]));
}

/** Returns a legal 27-point build together with flexible racial bonus choices. */
export function optimalAbilityBuild(character: Pick<ExportCharacter, "race" | "raceVariant" | "className">) {
  const variant = selectedRaceVariant(character.race, character.raceVariant);
  const keys = Object.keys(pointBuyCost).length ? (["str", "dex", "con", "int", "wis", "cha"] as AbilityKey[]) : [];
  const flexible = variant?.chooseBonuses;
  const eligible = keys.filter(key => !flexible?.exclude?.includes(key));
  const raceChoices = flexible ? distinctAbilitySelections(flexible.count, eligible) : [[]];
  const fixed = Object.fromEntries(keys.map(key => [key, variant?.bonuses?.[key] || 0])) as AbilityScores;
  const spellPrimary = classRules[character.className]?.spellAbility as AbilityKey | undefined;
  const primary = spellPrimary || physicalPrimary[character.className] || "con";
  const heavyArmor = /все доспехи|тяж[её]л/i.test(classRules[character.className]?.armor || "");
  const second: AbilityKey = !heavyArmor && primary !== "dex" ? "dex" : primary === "str" ? "con" : "str";
  const third: AbilityKey = primary === "con" || second === "con" ? "wis" : "con";
  let best: { score: number; abilities: AbilityScores; raceAbilityChoices: AbilityKey[] } | null = null;

  for (const chosen of raceChoices) {
    const bonuses = { ...fixed };
    chosen.forEach((key, index) => { bonuses[key] += flexible?.amounts?.[index] ?? flexible?.amount ?? 0; });
    for (const abilities of legalPointBuyBuilds) {
        const final = Object.fromEntries(keys.map(key => [key, abilities[key] + bonuses[key]])) as AbilityScores;
        const oddPenalty = keys.reduce((sum, key) => sum + (final[key] % 2 ? (final[key] === 15 || final[key] === 17 ? 140 : 70) : 0), 0);
        const conFloorPenalty = final.con < 14 ? (14 - final.con) * 90 : 0;
        const lowDexPenalty = !heavyArmor && final.dex < 14 ? (14 - final.dex) * 45 : 0;
        const score = final[primary] * 150 + final[second] * 55 + final[third] * 38
          + keys.reduce((sum, key) => sum + Math.floor((final[key] - 10) / 2) * 3, 0)
          - oddPenalty - conFloorPenalty - lowDexPenalty;
        if (!best || score > best.score) best = { score, abilities, raceAbilityChoices: chosen };
    }
  }
  return best || { score: 0, abilities: { str: 15, dex: 14, con: 13, int: 12, wis: 10, cha: 8 }, raceAbilityChoices: [] };
}

export function variantsFor(raceId: string) {
  return raceVariants[raceId] || [];
}

export function selectedRaceVariant(raceId: string, variantId: string) {
  return variantsFor(raceId).find(item => item.id === variantId) || (variantId === "base" ? baseRaceVariants[raceId] : undefined);
}

export function raceSkillChoiceCount(character: Pick<ExportCharacter, "race" | "raceVariant">) {
  if (character.race === "halfelf") return 2;
  if (character.race === "human" && character.raceVariant === "variant") return 1;
  return 0;
}

export function raceAbilityBonuses(character: ExportCharacter): AbilityScores {
  const result: AbilityScores = { str: 0, dex: 0, con: 0, int: 0, wis: 0, cha: 0 };
  const variant = selectedRaceVariant(character.race, character.raceVariant);
  for (const [key, value] of Object.entries(variant?.bonuses || {})) result[key as AbilityKey] += value || 0;
  if (variant?.chooseBonuses) {
    for (const [index, key] of (character.raceAbilityChoices || []).slice(0, variant.chooseBonuses.count).entries()) {
      result[key] += variant.chooseBonuses.amounts?.[index] ?? variant.chooseBonuses.amount ?? 0;
    }
  }
  return result;
}

export function finalAbilityScores(character: ExportCharacter): AbilityScores {
  const bonuses = raceAbilityBonuses(character);
  const featBonuses = featAbilityBonuses(character);
  const asiBonuses = (character.asiChoices || []).reduce<Partial<Record<AbilityKey, number>>>((result, key) => {
    result[key] = (result[key] || 0) + 1;
    return result;
  }, {});
  return Object.fromEntries(
    (Object.keys(character.abilities) as AbilityKey[]).map(key => [key, Math.min(20, character.abilities[key] + bonuses[key] + (asiBonuses[key] || 0) + (featBonuses[key] || 0))]),
  ) as AbilityScores;
}

export function raceProficiencies(character: ExportCharacter): string[] {
  const common: Record<string, string[]> = {
    dwarf: ["Боевой топор", "Ручной топор", "Лёгкий молот", "Боевой молот", "Один ремесленный инструмент"],
    elf: ["Внимательность"],
    halfelf: ["Два навыка на выбор"],
    goliath: ["Атлетика"],
    giff: ["Огнестрельное оружие"],
    astralelf: ["Один навык и один инструмент после транса"],
  };
  return [...new Set([...(common[character.race] || []), ...(selectedRaceVariant(character.race, character.raceVariant)?.proficiencies || []), ...(character.raceSkills || [])])];
}


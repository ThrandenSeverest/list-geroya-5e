const assert=require('node:assert/strict');
const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
(async()=>{
 const browser=await chromium.launch({headless:true,args:['--no-sandbox','--disable-dev-shm-usage']});
 try{for(const width of [1440,390]){
  const context=await browser.newContext({viewport:{width,height:1000}}),page=await context.newPage();page.setDefaultTimeout(15000);
  const root={id:'hb:test:class:workshop',type:'class',name:'Класс мастерской',description:'',updatedAt:'2026-10-06',hitDie:'d8',features:[{id:'hb:test:ability:pool',name:'Вдохновение',level:1,description:'Помогает союзнику.',resources:[{id:'hb:test:resource:pool',name:'Вдохновение',max:3,restore:['long_rest']}]},{id:'hb:test:ability:action',name:'Ободрение',level:1,description:'Расходует общее вдохновение.'}]};
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.route('**/api/account',route=>route.fulfill({json:{authenticated:false}}));
  await page.addInitScript(root=>{if(!localStorage.getItem('herolist-homebrew-local-v2'))localStorage.setItem('herolist-homebrew-local-v2',JSON.stringify({version:2,elements:[root]}))},root);
  await page.goto(process.env.HEROLIST_URL||'http://127.0.0.1:3998');await page.waitForFunction(()=>!document.body.innerText.includes('Проверяем вход'));
  await page.getByRole('button',{name:/^Мой Homebrew/}).click();
  await page.locator('.hb-sidebar-package > button').filter({hasText:root.name}).click();
  assert.equal(await page.getByRole('button',{name:'Связи',exact:true}).isVisible(),false);
  assert.equal(await page.getByRole('button',{name:'Копировать ID',exact:true}).isVisible(),false);
  await page.getByRole('button',{name:'Развитие и способности',exact:true}).click();
  const inspiration=page.locator('.hb-feature-card').filter({has:page.locator('summary > span').filter({hasText:/^Вдохновение$/})}).first();
  assert.equal(await inspiration.getByLabel('Название ресурса',{exact:true}).isVisible(),false);
  await inspiration.locator(':scope > summary').click();
  await inspiration.getByLabel('Максимум ресурса: способ расчёта',{exact:true}).selectOption('@pb');
  await inspiration.getByText('Улучшения на следующих уровнях · 0',{exact:true}).click();
  await inspiration.getByRole('button',{name:'+ Улучшение ресурса',exact:true}).click();
  await inspiration.getByLabel('Уровень улучшения ресурса',{exact:true}).fill('5');
  await inspiration.getByLabel('Изменить восстановление',{exact:true}).check();
  await inspiration.locator('.hb-resource-progression').getByRole('button',{name:'Короткий отдых',exact:true}).click();
  await inspiration.getByRole('button',{name:/Дать заклинания/}).click();
  await inspiration.getByLabel('Поиск бонусного заклинания',{exact:true}).fill('Огненный шар');
  await inspiration.getByRole('button',{name:'+ Огненный шар',exact:true}).click();
  await inspiration.getByLabel('Режим заклинания',{exact:true}).selectOption('always-prepared');
  await inspiration.locator(':scope > summary').click();
  const action=page.locator('.hb-feature-card').filter({has:page.locator('summary > span').filter({hasText:/^Ободрение$/})}).first();
  await action.locator(':scope > summary').click();
  await action.getByRole('button',{name:/Добавить действие/}).click();
  await action.getByRole('button',{name:'+ Действие',exact:true}).click();
  await action.getByLabel('Ресурс действия',{exact:true}).selectOption('hb:test:resource:pool');
  await action.getByLabel('Расход ресурса действия',{exact:true}).fill('2');
  await page.getByRole('button',{name:'Сохранить изменения',exact:true}).click();
  await page.getByRole('button',{name:'Сохранено',exact:true}).waitFor();
  const saved=await page.evaluate(()=>JSON.parse(localStorage.getItem('herolist-homebrew-local-v2')).elements[0]);
  assert.equal(saved.features[0].resources[0].max,'@pb');
  assert.deepEqual(saved.features[0].resources[0].progression,[{level:5,max:'@pb',restore:['long_rest','short_rest']}]);
  assert.equal(saved.features[0].spellGrants[0].mode,'always-prepared');
  assert.deepEqual(saved.features[1].actions[0].cost,{resource:'hb:test:resource:pool',amount:2});
  assert.equal(saved.features[0].id,root.features[0].id);
  assert.ok(await page.locator('.hb-editor').evaluate(el=>el.scrollWidth<=el.clientWidth+1));
  await page.screenshot({path:`/tmp/hb-workshop-${width}.png`,fullPage:true});
  await page.reload();await page.waitForFunction(()=>!document.body.innerText.includes('Проверяем вход'));await page.getByRole('button',{name:/^Мой Homebrew/}).click();
  assert.equal(await page.evaluate(()=>JSON.parse(localStorage.getItem('herolist-homebrew-local-v2')).elements[0].features[1].actions[0].cost.amount),2);
  assert.deepEqual(errors,[]);console.log(`Guided workshop ${width}: resource milestones, inline spells, shared action costs and reload passed`);await context.close();
 }}finally{await browser.close()}
})().catch(e=>{console.error(e);process.exit(1)});
